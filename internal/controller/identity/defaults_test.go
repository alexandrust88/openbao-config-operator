// The reads below are `bao read` of objects written with no optional field on OpenBao 2.7.2 (bao server -dev): an
// empty spec must match them, so that removing a field from a spec resets it and a second reconcile writes nothing.
func TestEmptySpecMatchesServerDefaults(t *testing.T) {
	ctx := context.Background()
	t.Run("oidc role", func(t *testing.T) {
		a := OIDCRoleAdapter{}
		desired, _ := a.Desired(ctx, nil, &identityv1alpha1.OIDCRole{ObjectMeta: oidcMeta("r0"),
			Spec: identityv1alpha1.OIDCRoleSpec{Key: "k0"}})
		if _, sent := desired[litClientID]; sent {
			t.Error("an unset client_id is generated by the server and must not be sent")
		}
		assertNoDiff(t, desired, map[string]any{litClientID: "XNCRarbSrXffWitQcHMnxOCDfk", litKey: "k0", litTemplate: "",
			"ttl": 86400}, a.Fields())
	})
	t.Run("oidc scope", func(t *testing.T) {
		a := OIDCScopeAdapter{}
		desired, _ := a.Desired(ctx, nil, &identityv1alpha1.OIDCScope{ObjectMeta: oidcMeta("s0")})
		assertNoDiff(t, desired, map[string]any{"description": "", litTemplate: ""}, a.Fields())
		assertDiff(t, desired, map[string]any{"description": "old", litTemplate: ""}, a.Fields(), "description")
	})
	t.Run("group", func(t *testing.T) {
		a := GroupAdapter{}
		desired, _ := a.Desired(ctx, nil, &identityv1alpha1.Group{ObjectMeta: idtMeta("g0")})
		assertNoDiff(t, desired, map[string]any{"type": "internal", "policies": nil, "metadata": nil}, a.Fields())
	})
	t.Run("entity alias", func(t *testing.T) {
		entity := idtReady(&identityv1alpha1.Entity{ObjectMeta: idtMeta(litAlice)}, idtEntityID)
		a := EntityAliasAdapter{Reader: idtReader(t, entity), Conns: idtConns{client: newIdtBao()}}
		ea := newEntityAlias()
		ea.Spec.CustomMetadata = nil
		desired, err := a.Desired(ctx, nil, ea)
		if err != nil {
			t.Fatal(err)
		}
		if _, sent := desired["custom_metadata"]; !sent {
			t.Error("custom_metadata must be sent, so that removing it from the spec clears it")
		}
		read := aliasRead()
		read["custom_metadata"] = map[string]any{}
		assertNoDiff(t, desired, read, a.Fields())
	})
	mfa := []struct {
		name string
		spec identityv1alpha1.MFAMethodSpec
		read map[string]any
	}{
		{name: "totp", spec: identityv1alpha1.MFAMethodSpec{TOTP: &identityv1alpha1.MFATOTP{Issuer: "x"}},
			read: map[string]any{litAlgorithm: litSHA1, "digits": 6, "issuer": "x", "key_size": 20,
				"max_validation_attempts": 5, litName: "otp", "period": 30, "qr_size": 200, "skew": 1, "type": "totp"}},
		{name: "duo", spec: identityv1alpha1.MFAMethodSpec{Duo: &identityv1alpha1.MFADuo{
			SecretKeySecretRef: secretRef("duo", "secret-key"), IntegrationKeySecretRef: secretRef("duo", "integration-key"),
			APIHostname: "h"}},
			read: map[string]any{"api_hostname": "h", litMountAccessor: "", litName: "otp", "pushinfo": "",
				"use_passcode": false, "username_format": ""}},
		{name: "okta", spec: identityv1alpha1.MFAMethodSpec{Okta: &identityv1alpha1.MFAOkta{OrgName: "o",
			APITokenSecretRef: secretRef("okta", "api-token")}},
			read: map[string]any{"base_url": "okta.com", litMountAccessor: "", litName: "otp", "org_name": "o",
				"username_format": ""}},
	}
	for _, tt := range mfa {
		t.Run("mfa "+tt.name, func(t *testing.T) {
			a := MFAMethodAdapter{}
			desired, err := a.Desired(ctx, mfaSecrets, &identityv1alpha1.MFAMethod{ObjectMeta: oidcMeta("otp"), Spec: tt.spec})
			if err != nil {
				t.Fatal(err)
			}
			assertNoDiff(t, desired, tt.read, a.Fields())
		})
	}
}

func TestMetadataMarker(t *testing.T) {
	marker := engine.OwnershipMarker{ManagedBy: "openbao-config-operator", ClusterID: "c1", UID: "uid-1"}
	for name, a := range map[string]interface {
		Mark(engine.Payload, engine.OwnershipMarker) engine.Payload
		MarkerOf(engine.Payload) (engine.OwnershipMarker, bool)
		Fields() engine.FieldSpec
	}{"entity": entityMarkerAdapter{}, "group": groupMarkerAdapter{}} {
		t.Run(name, func(t *testing.T) {
			user := map[string]string{litTeam: "a"}
			desired := engine.Payload{"metadata": user, "policies": []string{}}
			marked := a.Mark(desired, marker)
			if len(user) != 1 || len(desired["metadata"].(map[string]string)) != 1 {
				t.Fatal("Mark must not change the desired payload or the spec map")
			}
			// what OpenBao returns after the marked write: user keys and marker keys side by side.
			observed := engine.Payload{"policies": []any{}, "metadata": map[string]any{litTeam: "a",
				markerManagedByKey: "openbao-config-operator", markerClusterIDKey: "c1", markerUIDKey: "uid-1"}}
			if d := engine.Diff(marked, observed, a.Fields()); len(d) != 0 {
				t.Errorf("marked metadata must match its own read-back, differing %v", d)
			}
			got, ok := a.MarkerOf(observed)
			if !ok || got != marker {
				t.Errorf("marker = %+v, %v", got, ok)
			}
			if _, ok := a.MarkerOf(engine.Payload{"metadata": map[string]any{litTeam: "a"}}); ok {
				t.Error("metadata without the marker carries none")
			}
			noCluster := a.Mark(engine.Payload{"metadata": map[string]string{}}, engine.OwnershipMarker{ManagedBy: "m", UID: "u"})
			if _, ok := noCluster["metadata"].(map[string]string)[markerClusterIDKey]; ok {
				t.Error("an empty cluster id must not be written")
			}
			observed["metadata"].(map[string]any)["intruder"] = "x"
			if d := engine.Diff(marked, observed, a.Fields()); len(d) != 1 {
				t.Errorf("a metadata key added out of band must show as drift, differing %v", d)
			}
		})
	}
}

func TestGroupMembershipSharesItsGroupPath(t *testing.T) {
	a := GroupMembershipAdapter{}
	if !a.SharedPath() {
		t.Error("several GroupMemberships write to one group and must opt out of path ownership")
	}
	if !a.Singleton() {
		t.Error("a satisfied membership must be taken over, never refused with Conflict")
	}
}

func TestDriftTiers(t *testing.T) {
	for name, tier := range map[string]engine.DriftTier{"group": GroupAdapter{}, "groupmembership": GroupMembershipAdapter{}} {
		if tier.DriftTier() != engine.TierAccessCritical {
			t.Errorf("%s must be access-critical", name)
		}
	}
}

type entityMarkerAdapter struct{ EntityAdapter }

func (a entityMarkerAdapter) Mark(desired engine.Payload, m engine.OwnershipMarker) engine.Payload {
	return a.EntityAdapter.Mark(nil, desired, m)
}

type groupMarkerAdapter struct{ GroupAdapter }

func (a groupMarkerAdapter) Mark(desired engine.Payload, m engine.OwnershipMarker) engine.Payload {
	return a.GroupAdapter.Mark(nil, desired, m)
}
