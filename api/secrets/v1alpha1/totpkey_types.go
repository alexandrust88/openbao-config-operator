// Settings for a TOTP key generated by OpenBao. writeSecretRef is required unless exported is false.
// +kubebuilder:validation:XValidation:rule="(has(self.exported) && !self.exported) || has(self.writeSecretRef)",message="writeSecretRef is required unless exported is false"
type TOTPGenerate struct {
	// keySize is the size of the generated key in bytes (`key_size`). 1-256. Defaults to 20.
	// +kubebuilder:validation:Minimum=1
	// +kubebuilder:validation:Maximum=256
	// +optional
	KeySize *int32 `json:"keySize,omitempty"`

	// exported returns the otpauth URL and QR code once, at creation (`exported`). Defaults to true.
	// +optional
	Exported *bool `json:"exported,omitempty"`

	// qrSize is the pixel size of the QR code; 0 returns none (`qr_size`). 0-2048. Defaults to 200.
	// +kubebuilder:validation:Minimum=0
	// +kubebuilder:validation:Maximum=2048
	// +optional
	QRSize *int32 `json:"qrSize,omitempty"`

	// writeSecretRef names the Secret, owned by this resource, that receives the otpauth URL (key `url`) and the base64 PNG QR code (key `barcode`) once, when the key is generated. OpenBao never returns them again; they are never stored in status. Example: `{name: alice-totp}`.
	// +optional
	WriteSecretRef *commonv1alpha1.LocalObjectReference `json:"writeSecretRef,omitempty"`
}

