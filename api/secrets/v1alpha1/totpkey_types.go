func (k *TOTPKey) GetResourceSpec() *commonv1alpha1.ResourceSpec { return &k.Spec.ResourceSpec }

// GetResourceStatus implements commonv1alpha1.Managed.
func (k *TOTPKey) GetResourceStatus() *commonv1alpha1.ResourceStatus { return &k.Status.ResourceStatus }

