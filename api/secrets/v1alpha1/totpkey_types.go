// spec is the desired key of a TOTP secrets engine at `<mountPath>/keys/<name>`. Set exactly one of generate (OpenBao generates the key), keySecretRef (import a base32 key) or urlSecretRef (import an otpauth URL).
type TOTPKeySpec struct {
	commonv1alpha1.ResourceSpec `json:",inline"`

	// mountPath is the path of the TOTP secrets engine mount. Defaults to `totp`. Immutable. Example: `totp`.
	// +kubebuilder:default=totp
	// +kubebuilder:validation:MaxLength=128
	// +kubebuilder:validation:Pattern=`^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$`
	// +optional
	MountPath string `json:"mountPath,omitempty"`

	// name is the key name in OpenBao. Defaults to metadata.name. Immutable. Example: `alice`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=128
	// +kubebuilder:validation:Pattern=`^[A-Za-z0-9_.@-]+$`
	// +optional
	Name string `json:"name,omitempty"`

	// generate makes OpenBao generate the key once (`generate=true`). Its settings cannot change afterwards: a new write would replace the key and break every enrolled authenticator.
	// +optional
	Generate *TOTPGenerate `json:"generate,omitempty"`

	// keySecretRef selects the Secret key holding the base32 shared key to import (`key`). Read from a Secret key; never stored in status. Write-only. Example: `{name: alice-totp, key: seed}`.
	// +optional
	KeySecretRef *commonv1alpha1.SecretKeySelector `json:"keySecretRef,omitempty"`

	// urlSecretRef selects the Secret key holding an `otpauth://` URL to import (`url`); issuer, account and code settings come from the URL. Read from a Secret key; never stored in status. Write-only. Example: `{name: alice-totp, key: url}`.
	// +optional
	URLSecretRef *commonv1alpha1.SecretKeySelector `json:"urlSecretRef,omitempty"`

	// issuer is the name of the issuing organisation (`issuer`). Required with generate; immutable then. Example: `Example Corp`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=256
	// +optional
	Issuer string `json:"issuer,omitempty"`

	// accountName is the account the key belongs to (`account_name`). Required with generate; immutable then. Example: `alice@example.com`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=256
	// +optional
	AccountName string `json:"accountName,omitempty"`

	// period is the time step of the code (`period`), a duration. Defaults to `30s`. Immutable for a generated key.
	// +kubebuilder:validation:Type=string
	// +kubebuilder:validation:Pattern=`^(0|([0-9]+(\.[0-9]+)?(ns|us|ms|s|m|h))+)$`
	// +optional
	Period *metav1.Duration `json:"period,omitempty"`

	// algorithm is the hash algorithm of the code (`algorithm`). Allowed: SHA1, SHA256, SHA512. Defaults to SHA1. Immutable for a generated key.
	// +kubebuilder:validation:Enum=SHA1;SHA256;SHA512
	// +optional
	Algorithm string `json:"algorithm,omitempty"`

	// digits is the length of the code (`digits`). Allowed: 6, 8. Defaults to 6. Immutable for a generated key.
	// +kubebuilder:validation:Enum=6;8
	// +optional
	Digits *int32 `json:"digits,omitempty"`

	// skew is the number of periods of clock drift accepted when validating a code (`skew`). Allowed: 0, 1. Defaults to 1. Immutable for a generated key.
	// +kubebuilder:validation:Minimum=0
	// +kubebuilder:validation:Maximum=1
	// +optional
	Skew *int32 `json:"skew,omitempty"`
}

// status is the observed state of the TOTP key.
type TOTPKeyStatus struct {
	commonv1alpha1.ResourceStatus `json:",inline"`
}

