// TOTPKey manages a key of a TOTP secrets engine at `<mount>/keys/<name>`, either generated by OpenBao or imported from a Secret. Use it to issue or validate time-based one-time passwords; a generated key's URL and QR code are written once to writeSecretRef.
//
// Example:
//
//	spec:
//	  connectionRef:
//	    name: openbao
//	  name: alice
//	  issuer: Example Corp
//	  accountName: alice@example.com
//	  generate:
//	    writeSecretRef:
//	      name: alice-totp
type TOTPKey struct {
	metav1.TypeMeta `json:",inline"`

	// +optional
	metav1.ObjectMeta `json:"metadata,omitzero"`

	// +required
	Spec TOTPKeySpec `json:"spec"`

	// +optional
	Status TOTPKeyStatus `json:"status,omitzero"`
}

