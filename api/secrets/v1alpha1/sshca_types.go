// +kubebuilder:validation:XValidation:rule="has(self.mountPath) == has(oldSelf.mountPath) && (!has(self.mountPath) || self.mountPath == oldSelf.mountPath)",message="mountPath is immutable"
// +kubebuilder:validation:XValidation:rule="has(self.privateKeySecretRef) == has(oldSelf.privateKeySecretRef)",message="switching between a generated and an imported CA key is not allowed"
// +kubebuilder:validation:XValidation:rule="has(self.keyType) == has(oldSelf.keyType) && (!has(self.keyType) || self.keyType == oldSelf.keyType)",message="keyType is immutable"
// +kubebuilder:validation:XValidation:rule="has(self.keyBits) == has(oldSelf.keyBits) && (!has(self.keyBits) || self.keyBits == oldSelf.keyBits)",message="keyBits is immutable"
// +kubebuilder:validation:XValidation:rule="has(self.publicKey) == has(self.privateKeySecretRef)",message="publicKey and privateKeySecretRef must be set together"
// +kubebuilder:validation:XValidation:rule="!has(self.privateKeySecretRef) || (!has(self.keyType) && !has(self.keyBits))",message="keyType and keyBits apply only to a generated CA key"

// spec is the desired default signing CA of an SSH secrets engine at `<mountPath>/config/ca`. Without privateKeySecretRef, OpenBao generates the key pair once; with it, the given key pair is imported. Switching between the two is not allowed.
type SSHCASpec struct {
	commonv1alpha1.ResourceSpec `json:",inline"`

	// mountPath is the path of the SSH secrets engine mount. Defaults to `ssh`. Immutable. Example: `ssh-client-signer`.
	// +kubebuilder:default=ssh
	// +kubebuilder:validation:MaxLength=128
	// +kubebuilder:validation:Pattern=`^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$`
	// +optional
	MountPath string `json:"mountPath,omitempty"`

	// keyType is the type of the generated key pair (`key_type`): an OpenSSH key type or rsa, ec, ed25519. Generated keys only. Defaults to ssh-rsa. Immutable. Example: `ssh-ed25519`.
	// +kubebuilder:validation:Enum=ssh-rsa;ecdsa-sha2-nistp256;ecdsa-sha2-nistp384;ecdsa-sha2-nistp521;ssh-ed25519;rsa;ec;ed25519
	// +optional
	KeyType string `json:"keyType,omitempty"`

	// keyBits is the RSA key size, or the NIST curve (256, 384, 521) for keyType ec, of the generated key pair (`key_bits`). 0 uses the key type default (4096 for RSA). Immutable. Example: `4096`.
	// +kubebuilder:validation:Minimum=0
	// +kubebuilder:validation:Maximum=8192
	// +optional
	KeyBits *int32 `json:"keyBits,omitempty"`

	// publicKey is the OpenSSH public key of an imported CA key pair (`public_key`); set together with privateKeySecretRef. Example: `ssh-ed25519 AAAAC3Nza... ca@example`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=16384
	// +optional
	PublicKey string `json:"publicKey,omitempty"`

	// privateKeySecretRef selects the Secret key holding the PEM private key of an imported CA key pair (`private_key`). Read from a Secret key; never stored in status. Write-only: never read back; a change of the Secret imports the new key pair. Example: `{name: ssh-ca, key: id_ed25519}`.
	// +optional
	PrivateKeySecretRef *commonv1alpha1.SecretKeySelector `json:"privateKeySecretRef,omitempty"`
}

// status is the observed state of the SSH CA.
type SSHCAStatus struct {
	commonv1alpha1.ResourceStatus `json:",inline"`

	// publicKey is the OpenSSH public key of the CA, for `TrustedUserCAKeys` or known_hosts.
	// +optional
	PublicKey string `json:"publicKey,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:categories=openbao
// +kubebuilder:printcolumn:name="Ready",type=string,JSONPath=`.status.conditions[?(@.type=="Ready")].status`
// +kubebuilder:printcolumn:name="Synced",type=string,JSONPath=`.status.conditions[?(@.type=="Synced")].status`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=`.metadata.creationTimestamp`

// SSHCA configures the default signing CA of an SSH secrets engine at `<mount>/config/ca`, generated by OpenBao or imported from a Secret. Use it with SSHRole objects of key type ca to sign SSH user or host certificates; status.publicKey is the key to trust.
//
// Example:
//
//	spec:
//	  connectionRef:
//	    name: openbao
//	  mountPath: ssh-client-signer
//	  keyType: ssh-ed25519
type SSHCA struct {
	metav1.TypeMeta `json:",inline"`

	// +optional
	metav1.ObjectMeta `json:"metadata,omitzero"`

	// +required
	Spec SSHCASpec `json:"spec"`

	// +optional
	Status SSHCAStatus `json:"status,omitzero"`
}

// GetResourceSpec implements commonv1alpha1.Managed.
func (c *SSHCA) GetResourceSpec() *commonv1alpha1.ResourceSpec { return &c.Spec.ResourceSpec }

// GetResourceStatus implements commonv1alpha1.Managed.
func (c *SSHCA) GetResourceStatus() *commonv1alpha1.ResourceStatus { return &c.Status.ResourceStatus }

// +kubebuilder:object:root=true

// SSHCAList contains a list of SSHCA.
type SSHCAList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitzero"`
	Items           []SSHCA `json:"items"`
}

func init() {
	SchemeBuilder.Register(&SSHCA{}, &SSHCAList{})
}
