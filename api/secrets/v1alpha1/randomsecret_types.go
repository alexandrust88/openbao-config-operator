// +kubebuilder:validation:XValidation:rule="self.mountPath == oldSelf.mountPath",message="mountPath is immutable"
// +kubebuilder:validation:XValidation:rule="self.path == oldSelf.path",message="path is immutable"
// +kubebuilder:validation:XValidation:rule="has(self.kvVersion) == has(oldSelf.kvVersion) && (!has(self.kvVersion) || self.kvVersion == oldSelf.kvVersion)",message="kvVersion is immutable"
// +kubebuilder:validation:XValidation:rule="has(self.key) == has(oldSelf.key) && (!has(self.key) || self.key == oldSelf.key)",message="key is immutable"
// +kubebuilder:validation:XValidation:rule="!(has(self.passwordPolicyName) && has(self.generator))",message="set at most one of passwordPolicyName and generator"

// spec is the desired generated value, stored under one key of a KV secret.
//
// The value is generated once, when the key is absent, and kept afterwards: an existing value is adopted, and changing the generator settings does not regenerate it. Change refreshNonce to generate a new value. Other keys at the same path are kept.
type RandomSecretSpec struct {
	commonv1alpha1.ResourceSpec `json:",inline"`

	// mountPath is the path of the KV secrets engine mount, without leading or trailing slashes. Immutable. Example: `secret`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=128
	// +kubebuilder:validation:Pattern=`^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$`
	// +required
	MountPath string `json:"mountPath"`

	// path is the secret path inside the mount, without the `data/` prefix of KV version 2 (the operator adds it). Immutable. Example: `apps/billing/db`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=512
	// +kubebuilder:validation:Pattern=`^[^/]+(/[^/]+)*$`
	// +required
	Path string `json:"path"`

	// kvVersion is the version of the KV engine at mountPath. Allowed: 1, 2. Defaults to 2. Immutable.
	// +kubebuilder:validation:Enum=1;2
	// +kubebuilder:default=2
	// +optional
	KVVersion int32 `json:"kvVersion,omitempty"`

	// key is the key of the OpenBao secret that holds the generated value. Defaults to `password`. Immutable. Example: `admin-password`.
	// +kubebuilder:default=password
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=253
	// +kubebuilder:validation:Pattern=`^[-._a-zA-Z0-9]+$`
	// +optional
	Key string `json:"key,omitempty"`

	// passwordPolicyName generates the value with this OpenBao password policy (`sys/policies/password/<name>/generate`), looked up in the resource's OpenBao namespace. Unset uses generator. Read only when a value is generated (on create and when refreshNonce changes): changing or removing it later keeps the stored value and writes nothing. Example: `strong`.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=128
	// +optional
	PasswordPolicyName string `json:"passwordPolicyName,omitempty"`

	// generator describes a value generated by the operator from a cryptographically secure source; used when passwordPolicyName is unset. Read only when a value is generated (on create and when refreshNonce changes): changing or removing it later keeps the stored value and writes nothing. Example: `{length: 40}`.
	// +optional
	Generator *RandomSecretGenerator `json:"generator,omitempty"`

	// refreshNonce is an arbitrary string; changing it generates a new value. Example: `2026-11-rotation`.
	// +kubebuilder:validation:MaxLength=253
	// +optional
	RefreshNonce string `json:"refreshNonce,omitempty"`

	// writeSecretRef also stores the value under key in this Secret, which the resource then owns. The Secret is written when the value is generated or adopted and when writeSecretRef changes. The value is never stored in status. Example: `{name: db-admin}`.
	// +optional
	WriteSecretRef *commonv1alpha1.LocalObjectReference `json:"writeSecretRef,omitempty"`
}

// A value drawn uniformly from a set of characters.
type RandomSecretGenerator struct {
	// length is the length of the value in characters. 8-1024. Defaults to 32.
	// +kubebuilder:default=32
	// +kubebuilder:validation:Minimum=8
	// +kubebuilder:validation:Maximum=1024
	// +optional
	Length int32 `json:"length,omitempty"`

	// charset lists the characters to draw from; duplicates are ignored. 10-256 characters. Defaults to ASCII letters and digits. Example: `abcdef0123456789`.
	// +kubebuilder:default="abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	// +kubebuilder:validation:MinLength=10
	// +kubebuilder:validation:MaxLength=256
	// +optional
	Charset string `json:"charset,omitempty"`
}

// status is the observed state of the random secret (never the value).
type RandomSecretStatus struct {
	commonv1alpha1.ResourceStatus `json:",inline"`

	// refreshNonce is the spec.refreshNonce the current value was generated or adopted with.
	// +optional
	RefreshNonce string `json:"refreshNonce,omitempty"`

	// pathCreated is true when this resource created the KV secret rather than adding its key to an existing one; only then does a destructive delete also remove the secret's version history.
	// +optional
	PathCreated bool `json:"pathCreated,omitempty"`

	// purgeThroughVersion is the persisted upper version bound for destructive KV v2 cleanup. Newer versions and metadata are retained.
	// +kubebuilder:validation:Minimum=1
	// +optional
	PurgeThroughVersion *int64 `json:"purgeThroughVersion,omitempty"`
}

