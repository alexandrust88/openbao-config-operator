// +kubebuilder:subresource:status
// +kubebuilder:resource:shortName=baorand,categories=obco;obco-secrets
// +kubebuilder:printcolumn:name="Ready",type=string,JSONPath=`.status.conditions[?(@.type=="Ready")].status`
// +kubebuilder:printcolumn:name="Synced",type=string,JSONPath=`.status.conditions[?(@.type=="Synced")].status`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=`.metadata.creationTimestamp`

// RandomSecret generates a value, such as a password, once and stores it under one key of a KV secret (`<mount>/data/<path>` on version 2). Use it for credentials nobody needs to choose; set writeSecretRef to also get the value in a Kubernetes Secret.
//
// Example:
//
//	spec:
//	  connectionRef:
//	    name: openbao
//	  mountPath: secret
//	  path: apps/billing/db
//	  key: password
//	  generator:
//	    length: 40
type RandomSecret struct {
	metav1.TypeMeta `json:",inline"`

	// +optional
	metav1.ObjectMeta `json:"metadata,omitzero"`

	// +required
	Spec RandomSecretSpec `json:"spec"`

	// +optional
	Status RandomSecretStatus `json:"status,omitzero"`
}

// GetResourceSpec implements commonv1alpha1.Managed.
func (s *RandomSecret) GetResourceSpec() *commonv1alpha1.ResourceSpec { return &s.Spec.ResourceSpec }

// GetResourceStatus implements commonv1alpha1.Managed.
func (s *RandomSecret) GetResourceStatus() *commonv1alpha1.ResourceStatus {
	return &s.Status.ResourceStatus
}

// +kubebuilder:object:root=true

// RandomSecretList contains a list of RandomSecret.
type RandomSecretList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitzero"`
	Items           []RandomSecret `json:"items"`
}

func init() {
	SchemeBuilder.Register(&RandomSecret{}, &RandomSecretList{})
}
