#!/usr/bin/env bash
# Merges config/rbac/role.yaml with hack/chart/rbac-required.yaml and writes templates/rbac/_manager-rules.tpl.
# Namespaced core resources (secrets, configmaps, serviceaccounts, events), leases and the namespaced managed kinds
# (scope from templates/_crd-resources.tpl, written by sync-crds.sh) are split out so the chart can grant them per
# watched namespace instead of cluster-wide.
# Usage: hack/chart/sync-rbac.sh [role.yaml]   (default: config/rbac/role.yaml)
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/../.." && pwd)
role=${1:-$repo_root/config/rbac/role.yaml}
required=$repo_root/hack/chart/rbac-required.yaml
crd_index=$repo_root/charts/openbao-config-operator/templates/_crd-resources.tpl
out=$repo_root/charts/openbao-config-operator/templates/rbac/_manager-rules.tpl
yq=${YQ:-yq}
jq=${JQ:-jq}

for bin in "$yq" "$jq"; do
  command -v "$bin" >/dev/null || { echo "sync-rbac: $bin is required" >&2; exit 1; }
done

rules_json=$("$yq" ea -o=json -I=0 '[.rules // [] | .[]]' "$role" "$required" | "$jq" -sc 'add')
scopes_json=$(sed -n 's/^- {/{/p' "$crd_index" | "$jq" -sc 'map({key: "\(.group)/\(.plural)", value: .scope}) | from_entries')

# shellcheck disable=SC2016 # jq variables, not shell
unknown=$("$jq" -r --argjson scopes "$scopes_json" '
  [ .[] | select(has("nonResourceURLs") | not) | .apiGroups[] as $g | .resources[] as $r
    | select($g | endswith("obco.dev")) | "\($g)/\($r | split("/")[0])"
    | select($scopes[.] == null) ] | unique | join(" ")' <<<"$rules_json")
[ -z "$unknown" ] || { echo "sync-rbac: no scope in $crd_index for: $unknown (run sync-crds.sh first)" >&2; exit 1; }

rules_for() {
  # shellcheck disable=SC2016 # jq variables, not shell
  "$jq" --arg want "$1" --argjson scopes "$scopes_json" '
    def namespaced: (.g == "" and (.r | IN("namespaces", "nodes", "persistentvolumes") | not))
      or (.g | IN("events.k8s.io", "coordination.k8s.io"))
      or ($scopes["\(.g)/\(.r | split("/")[0])"] == "Namespaced");
    [ .[] | select(has("nonResourceURLs") | not) | . as $rule
      | $rule.apiGroups[] as $g | $rule.resources[] as $r
      | {g: $g, r: $r, n: ($rule.resourceNames // null), v: $rule.verbs} ]
    | group_by([.g, .r, .n])
    | map({g: .[0].g, r: .[0].r, n: .[0].n, v: ([.[].v[]] | unique)})
    | map(select(if $want == "namespaced" then namespaced else (namespaced | not) end))
    | group_by([.g, .n, .v])
    | map({apiGroups: [.[0].g], resources: ([.[].r] | sort)}
      + (if .[0].n then {resourceNames: .[0].n} else {} end)
      + {verbs: .[0].v})
    | sort_by(.apiGroups[0], .resources[0])
  ' <<<"$rules_json" | "$yq" -p=json -o=yaml -I=2 'select(length > 0)'
}

{
  echo '{{/* generated by hack/chart/sync-rbac.sh; do not edit */}}'
  echo '{{- define "openbao-config-operator.managerRules.cluster" -}}'
  rules_for cluster
  "$jq" '[.[] | select(has("nonResourceURLs"))] | unique' <<<"$rules_json" | "$yq" -p=json -o=yaml -I=2 'select(length > 0)'
  echo '{{- end }}'
  echo
  echo '{{- define "openbao-config-operator.managerRules.namespaced" -}}'
  rules_for namespaced
  echo '{{- end }}'
} >"$out"

echo "sync-rbac: wrote $out"
