#!/usr/bin/env bash
# Copies the generated CRDs into the chart as templates guarded by crds.install and crds.keep (plugin kinds listed in
# hack/chart/plugin-crds.txt also by pluginKinds.enabled), and writes
# templates/_crd-resources.tpl, the resource index used by the user-facing ClusterRoles.
# Usage: hack/chart/sync-crds.sh [crd_dir]   (default: config/crd/bases)
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/../.." && pwd)
src_dir=${1:-$repo_root/config/crd/bases}
chart_dir=$repo_root/charts/openbao-config-operator
out_dir=$chart_dir/templates/crds
index=$chart_dir/templates/_crd-resources.tpl
plugin_list=$repo_root/hack/chart/plugin-crds.txt
yq=${YQ:-yq}

command -v "$yq" >/dev/null || { echo "sync-crds: mikefarah yq v4 is required" >&2; exit 1; }

while read -r name; do
  [ -e "$src_dir/$name" ] || { echo "sync-crds: $name in $plugin_list has no file in $src_dir" >&2; exit 1; }
done <"$plugin_list"

mkdir -p "$out_dir"
find "$out_dir" -name '*.yaml' -type f -delete

entries=""
for src in "$src_dir"/*.yaml; do
  [ -e "$src" ] || continue
  [ "$("$yq" '.kind' "$src")" = "CustomResourceDefinition" ] || continue

  guard='.Values.crds.install'
  plugin=''
  if grep -qxF "$(basename "$src")" "$plugin_list"; then
    guard='and .Values.crds.install .Values.pluginKinds.enabled'
    plugin=' | .plugin = true'
  fi
  {
    echo "{{- if $guard }}"
    "$yq" '.metadata.annotations["helm.sh/resource-policy"] = "keep" | .metadata.labels = "__chart_labels__"' "$src" |
      awk '
        /^---$/ { next }
        /^    helm\.sh\/resource-policy: keep$/ {
          print "    {{- if .Values.crds.keep }}"; print; print "    {{- end }}"; next
        }
        /^  labels: __chart_labels__$/ {
          print "  labels:"; print "    {{- include \"openbao-config-operator.labels\" . | nindent 4 }}"; next
        }
        { gsub(/[{][{]/, "{{ \"{{\" }}"); print }
      '
    echo '{{- end }}'
  } >"$out_dir/$(basename "$src")"

  entries+="- $("$yq" -o=json -I=0 "{\"group\": .spec.group, \"plural\": .spec.names.plural, \"scope\": .spec.scope}$plugin" "$src")"$'\n'
done

{
  echo '{{/* generated by hack/chart/sync-crds.sh; do not edit */}}'
  echo '{{- define "openbao-config-operator.crdResources" -}}'
  printf '%s' "${entries:-[]$'\n'}"
  echo '{{- end }}'
} >"$index"

echo "sync-crds: $(find "$out_dir" -name '*.yaml' -type f | wc -l | tr -d ' ') CRDs written to $out_dir"
